/** The check catalog as markdown: the generated section of docs/qa.md (`pnpm qa --update-docs` rewrites it). */
import { CHECKS, TIER_INFO, TIERS, type Requirement } from "./catalog.js";

export const DOC_START = "<!-- qa:catalog:start (generated by `pnpm qa --update-docs`; do not edit by hand) -->";
export const DOC_END = "<!-- qa:catalog:end -->";

export function need(requirement: Requirement): string | undefined {
  if (requirement === "built" || requirement === "platform") return undefined;
  if (requirement.startsWith("environment:")) return `\`${requirement.slice("environment:".length)}\` environment`;
  if (requirement.startsWith("app:")) return `${requirement.slice("app:".length)} app`;
  const labels: Record<string, string> = {
    docker: "Docker",
    github: "GitHub sign-in",
    background: "background sign-in",
    edge: "Microsoft Edge",
    "apps-domain": "`--apps-domain`",
    "isolated-environment": "`--isolated-env`",
  };
  return labels[requirement];
}

const cell = (text: string) => text.replace(/\|/g, "\\|");

export function catalogMarkdown(): string {
  const lines: string[] = [];
  for (const tier of TIERS) {
    const checks = CHECKS.filter((check) => check.tier === tier);
    lines.push(`### \`${tier}\``, "", `${TIER_INFO[tier].summary}. Needs ${TIER_INFO[tier].needs}.`, "");
    lines.push("| Check | What it checks | Also needs | Model cost |", "| --- | --- | --- | --- |");
    for (const check of checks) {
      if (check.kind === "manual") continue;
      const needs = check.requires.map(need).filter(Boolean).join(", ");
      lines.push(`| \`${check.id}\` | ${cell(check.title)} | ${needs || "-"} | ${check.cost ?? "-"} |`);
    }
    const manual = checks.filter((check) => check.kind === "manual");
    if (manual.length > 0) {
      lines.push("", "By hand:", "", "| Check | What to check | Steps |", "| --- | --- | --- |");
      for (const check of manual) lines.push(`| \`${check.id}\` | ${cell(check.title)} | ${cell(check.steps)} |`);
    }
    lines.push("");
  }
  return lines.join("\n").trimEnd();
}

/** Replaces the generated section of a document, keeping its line endings; throws when its markers are missing. */
export function withCatalog(document: string): string {
  const start = document.indexOf(DOC_START);
  const end = document.indexOf(DOC_END);
  if (start < 0 || end < start) throw new Error(`docs/qa.md is missing its catalog markers (${DOC_START} ... ${DOC_END}).`);
  const eol = document.includes("\r\n") ? "\r\n" : "\n";
  const section = `${eol}${eol}${catalogMarkdown().split("\n").join(eol)}${eol}${eol}`;
  return `${document.slice(0, start + DOC_START.length)}${section}${document.slice(end)}`;
}
