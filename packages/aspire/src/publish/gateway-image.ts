/**
 * Build files for the deployed gateway: the gateway's own Dockerfile (whose `azure` stage adds the single-writer lease
 * supervisor) plus a final stage that copies this AppHost's customization folders into the image, and an allowlist
 * `.dockerignore` so the build context is only what the image needs. Written under `.managed-copilot/publish/<name>/`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { APPHOST_DIR_IN_IMAGE, AzurePublishError } from "./config.js";

export interface GatewayBuildFiles {
  /** The repository root, used as the Docker build context. */
  readonly context: string;
  /** The generated Dockerfile, relative to the context (POSIX separators). */
  readonly dockerfile: string;
}

function gatewayDirectory(): string {
  try {
    return dirname(createRequire(import.meta.url).resolve("@managed-copilot/gateway/package.json"));
  } catch {
    throw new AzurePublishError("Cannot find the @managed-copilot/gateway package. Run `pnpm install` at the repository root.");
  }
}

/** Generates the gateway's Dockerfile for this deployment. Customization folders are AppHost-relative POSIX paths. */
export function writeGatewayBuildFiles(options: { appHostDirectory: string; name: string; customizations: readonly string[] }): GatewayBuildFiles {
  const gateway = gatewayDirectory();
  // The gateway Dockerfile builds from the repository root (it copies packages/protocol and deploy/azure as well).
  const context = dirname(dirname(gateway));
  if (!existsSync(join(context, "pnpm-workspace.yaml")) || !existsSync(join(context, "deploy", "azure", "package.json"))) {
    throw new AzurePublishError(`Publishing builds the gateway from the Managed Copilot repository, but ${context} is not its root.`);
  }
  const base = readFileSync(join(gateway, "Dockerfile"), "utf8").replace(/\r\n/g, "\n");
  if (!/^FROM\s+\S+\s+AS\s+azure\s*$/im.test(base)) throw new AzurePublishError(`${join(gateway, "Dockerfile")} has no "azure" stage.`);
  const ignore = readFileSync(join(gateway, "Dockerfile.dockerignore"), "utf8").replace(/\r\n/g, "\n");

  const copies: string[] = [];
  const allow: string[] = [];
  for (const folder of options.customizations) {
    const absolute = join(options.appHostDirectory, ...folder.split("/"));
    const fromContext = relative(context, absolute).split(sep).join("/");
    if (!fromContext || fromContext.startsWith("..")) {
      throw new AzurePublishError(`The customizations folder ${absolute} must be inside ${context} to be built into the gateway image.`);
    }
    copies.push(`COPY ${JSON.stringify([fromContext, `${APPHOST_DIR_IN_IMAGE}/${folder}`])}`);
    allow.push(`!${fromContext}/**`);
  }

  const dockerfile = [
    base.trimEnd(),
    "",
    `# Generated by @managed-copilot/aspire for "${options.name}": the AppHost files the deployed gateway reads.`,
    "FROM azure AS deployment",
    ...copies,
    `ENV MANAGED_COPILOT_APPHOST_DIR=${APPHOST_DIR_IN_IMAGE}`,
    "",
  ].join("\n");
  const directory = join(context, ".managed-copilot", "publish", options.name);
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, "gateway.Dockerfile"), dockerfile);
  writeFileSync(join(directory, "gateway.Dockerfile.dockerignore"), `${ignore.trimEnd()}\n${allow.join("\n")}\n`);
  return { context, dockerfile: relative(context, join(directory, "gateway.Dockerfile")).split(sep).join("/") };
}
