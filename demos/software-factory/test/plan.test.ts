import { describe, expect, it } from "vitest";
import { normalizeWorkspacePath, topologicalOrder, validatePlan, validateReview } from "../src/server/pipeline/plan.js";
import { builderSeed, packageJson, releaseSeed, sha256 } from "../src/server/pipeline/seed.js";
import type { Plan } from "../src/shared/types.js";

const task = (id: string, files: string[], dependsOn: string[] = []) => ({
  id,
  title: id,
  description: `Build ${id}`,
  files,
  acceptance: ["works"],
  dependsOn,
});

const valid = {
  summary: "Two slices.",
  projectName: "CSV JSON",
  packageDescription: "Convert",
  bin: { csv2json: "./bin/csv2json.js" },
  tasks: [task("csv2json", ["bin/csv2json.js", "test/csv2json.test.js"]), task("json2csv", ["src\\json2csv.js", "test/json2csv.test.js"])],
  integration: "Round trip.",
};

function problems(input: unknown): string[] {
  const result = validatePlan(input);
  return result.ok ? [] : [...result.problems];
}

describe("plan validation", () => {
  it("accepts and normalizes a good plan", () => {
    const result = validatePlan(valid);
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.value.projectName).toBe("csv-json");
    expect(result.value.bin).toEqual({ csv2json: "bin/csv2json.js" });
    expect(result.value.tasks[1]!.files).toEqual(["src/json2csv.js", "test/json2csv.test.js"]);
    expect(result.value.tasks[0]!.dependsOn).toEqual([]);
  });

  it("explains every problem so the planner can fix them", () => {
    expect(problems({ ...valid, tasks: [] })).toContain("Plan 1 to 4 tasks (got 0).");
    expect(problems({ ...valid, tasks: [task("a", ["src/a.js", "test/a.test.js"]), task("b", ["src/a.js", "test/b.test.js"])] })).toEqual([
      'tasks[1] (b): "src/a.js" is already owned by task "a"; tasks must own disjoint files.',
      "bin.csv2json: \"bin/csv2json.js\" is not owned by any task; add it to the task that implements the command.",
    ]);
    expect(problems({ ...valid, tasks: [task("a", ["src/a.js"])], bin: {} })).toEqual(["tasks[0] (a): own at least one test file named like test/a.test.js."]);
    expect(problems({ ...valid, tasks: [task("a", ["package.json", "../x.js", "test/a.test.js"])], bin: {} })).toEqual([
      "tasks[0] (a): package.json is generated by the factory; remove it from files.",
      'tasks[0] (a): "../x.js" is not a safe workspace-relative path.',
    ]);
    expect(problems({ ...valid, tasks: [task("Bad_Id", ["test/x.test.js"])], bin: {} })[0]).toMatch(/kebab-case/);
    expect(problems({ ...valid, tasks: [task("a", ["test/a.test.js"], ["ghost"])], bin: {} })).toEqual(['Task "a" depends on unknown task "ghost".']);
    expect(
      problems({ ...valid, tasks: [task("a", ["test/a.test.js"], ["b"]), task("b", ["test/b.test.js"], ["a"])], bin: {} }),
    ).toEqual(["Dependency cycle: a → b → a. Remove a dependsOn edge."]);
    expect(problems({ summary: 1 })[0]).toMatch(/^summary:/);
  });

  it("orders tasks so dependencies come first", () => {
    const plan = validatePlan({
      ...valid,
      bin: {},
      tasks: [task("cli", ["test/cli.test.js"], ["core"]), task("core", ["test/core.test.js"]), task("docs", ["test/docs.test.js"])],
    });
    expect(plan.ok && topologicalOrder(plan.value.tasks).map((item) => item.id)).toEqual(["core", "cli", "docs"]);
  });

  it("normalizes model-supplied paths and rejects escapes", () => {
    expect(normalizeWorkspacePath("./src/a.js")).toBe("src/a.js");
    expect(normalizeWorkspacePath("/workspace/src/a.js")).toBe("src/a.js");
    expect(normalizeWorkspacePath("src\\a.js")).toBe("src/a.js");
    for (const bad of ["/etc/passwd", "C:/x.js", "a/../../b", "a//b", ""]) expect(normalizeWorkspacePath(bad)).toBeUndefined();
  });
});

describe("review validation", () => {
  it("requires blocking findings to request changes, and only minor ones to approve", () => {
    expect(validateReview({ verdict: "approve", summary: "ok", findings: [] }).ok).toBe(true);
    expect(validateReview({ verdict: "request_changes", summary: "no", findings: [{ severity: "minor", message: "nit" }] })).toEqual({
      ok: false,
      problems: ["request_changes needs at least one blocker or major finding; approve when only minor issues remain."],
    });
    expect(validateReview({ verdict: "approve", summary: "ok", findings: [{ severity: "blocker", message: "crash" }] }).ok).toBe(false);
    const accepted = validateReview({
      verdict: "request_changes",
      summary: "fix",
      findings: Array.from({ length: 9 }, () => ({ severity: "major", file: "./src/a.js", message: " m " })),
    });
    expect(accepted.ok && accepted.value.findings).toHaveLength(6);
    expect(accepted.ok && accepted.value.findings[0]).toEqual({ severity: "major", file: "src/a.js", message: "m" });
  });
});

describe("sandbox seeds", () => {
  const plan = (validatePlan(valid) as { ok: true; value: Plan }).value;
  const wo = { number: 7, title: "Toolkit", brief: "Build it." };

  it("generates package.json with the harness scripts", () => {
    const manifest = JSON.parse(packageJson(plan, "/skills"));
    expect(manifest).toMatchObject({
      name: "csv-json",
      type: "module",
      bin: { csv2json: "bin/csv2json.js" },
      scripts: { check: "node /skills/factory-check/check.mjs", "check:release": "node /skills/factory-check/check.mjs --release" },
    });
  });

  it("records hashes of seeded project files so the harness publishes only the builder's changes", () => {
    const files = builderSeed(wo, plan, plan.tasks[1]!, new Map([["bin/csv2json.js", "x"]]));
    const seed = JSON.parse(files.find((file) => file.path === ".factory/seed.json")!.content);
    expect(seed.files).toEqual({ "package.json": sha256(files[0]!.content), "bin/csv2json.js": sha256("x") });
    expect(JSON.parse(files.find((file) => file.path === ".factory/task.json")!.content)).toMatchObject({ id: "json2csv", workOrder: "WO-0007" });
    expect(files.find((file) => file.path === ".factory/WORK_ORDER.md")!.content).toBe("# WO-0007: Toolkit\n\nBuild it.\n");
  });

  it("merges task files for the release and sets aside conflicting versions", () => {
    const outcomes = plan.tasks.map((item, index) => ({
      task: item,
      reviews: [],
      acceptedWithFindings: index === 1,
      files: new Map([
        [`src/${item.id}.js`, item.id],
        ["src/shared.js", `shared from ${item.id}`],
        ["README.md", "same"],
      ]),
    }));
    const seed = releaseSeed(wo, plan, outcomes);
    expect(seed.conflicts).toEqual(["src/shared.js"]);
    const paths = seed.files.map((file) => file.path);
    expect(paths).toEqual(expect.arrayContaining(["src/csv2json.js", "src/json2csv.js", "README.md", ".factory/conflicts/csv2json/src/shared.js", ".factory/conflicts/json2csv/src/shared.js"]));
    const release = JSON.parse(seed.files.find((file) => file.path === ".factory/release.json")!.content);
    expect(release.tasks.map((item: { outcome: string }) => item.outcome)).toEqual(["approved", "accepted_with_findings"]);
  });
});
